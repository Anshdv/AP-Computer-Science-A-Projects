package main.java.com.hillcrest.chapter2.math;

public class MathApplication {
    public static void main(String[] args) {
        System.out.println();
        System.out.println("5 to the power of 3 is: " + Math.pow(5, 3));
        System.out.println("The square root of 64 is: " + Math.sqrt(64));
        System.out.println("The absolute value of -10 is: " + Math.abs(-10));
        System.out.println("The maximum of 14 and 7 is: " + Math.max(14, 7));
        System.out.println("The minimum of 14 and 7 is: " + Math.min(14, 7));
    }
}
